/* NimbusOS - build-time font rasteriser (host tool).
 *
 * The kernel is built without floating point, so the TrueType outlines are
 * drawn here instead: stb_truetype turns each glyph into an anti-aliased
 * 8-bit coverage bitmap, and the result is written as C tables that the
 * kernel blits.  Glyph i is code point 32 + i.
 *
 *   usage: mkfont <out.c> <regular.ttf> <bold.ttf>
 */
#define STB_TRUETYPE_IMPLEMENTATION
#include "third_party/stb/stb_truetype.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define FIRST 32

/* Bytes 0x80-0x9F are control characters in Latin-1; the browser uses them for the
 * Windows-1252 characters (quotes, bullet, dashes, ellipsis, ...), so the table
 * draws those instead.  0x20 stands for the unused ones. */
static const int cp1252[32] = {
    0x20AC, 0x20, 0x201A, 0x0192, 0x201E, 0x2026, 0x2020, 0x2021, 0x02C6, 0x2030, 0x0160, 0x2039, 0x0152, 0x20, 0x017D, 0x20,
    0x20, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, 0x02DC, 0x2122, 0x0161, 0x203A, 0x0153, 0x20, 0x017E, 0x0178,
};
#define LAST 255
#define NGLYPH (LAST - FIRST + 1)

struct glyph {
    int adv, w, h, xoff, yoff;
    unsigned char *pix;
};

static unsigned char *read_file(const char *path, long *len)
{
    FILE *f = fopen(path, "rb");
    if (!f) { perror(path); exit(1); }
    fseek(f, 0, SEEK_END);
    *len = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *buf = malloc(*len);
    if (!buf || fread(buf, 1, *len, f) != (size_t)*len) { fprintf(stderr, "mkfont: cannot read %s\n", path); exit(1); }
    fclose(f);
    return buf;
}

/* Rasterises one face and writes its pixel array and glyph table. */
static void emit_face(FILE *out, const char *name, const char *path, int pixels)
{
    long len;
    unsigned char *ttf = read_file(path, &len);
    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, ttf, 0)) { fprintf(stderr, "mkfont: %s is not a TrueType font\n", path); exit(1); }

    float scale = stbtt_ScaleForMappingEmToPixels(&info, pixels);
    int asc, desc, gap;
    stbtt_GetFontVMetrics(&info, &asc, &desc, &gap);
    int ascent = (int)(asc * scale + 0.5f);
    int height = (int)((asc - desc) * scale + 0.5f);

    struct glyph gl[NGLYPH];
    int total = 0;
    for (int i = 0; i < NGLYPH; i++) {
        int cp = FIRST + i;
        if (cp >= 0x80 && cp <= 0x9F) cp = cp1252[cp - 0x80];
        int idx = stbtt_FindGlyphIndex(&info, cp);
        if (!idx) idx = stbtt_FindGlyphIndex(&info, '?');
        int advance, lsb, x0, y0, x1, y1;
        stbtt_GetGlyphHMetrics(&info, idx, &advance, &lsb);
        stbtt_GetGlyphBitmapBox(&info, idx, scale, scale, &x0, &y0, &x1, &y1);
        struct glyph *g = &gl[i];
        g->adv = (int)(advance * scale + 0.5f);
        g->w = x1 - x0;
        g->h = y1 - y0;
        g->xoff = x0;
        g->yoff = y0 + ascent;             /* from the line top */
        g->pix = NULL;
        if (g->w > 0 && g->h > 0) {
            g->pix = malloc((size_t)g->w * g->h);
            stbtt_MakeGlyphBitmap(&info, g->pix, g->w, g->h, g->w, scale, scale, idx);
            total += g->w * g->h;
        }
    }
    if (total > 65535) { fprintf(stderr, "mkfont: %s pixel data too large for u16 offsets\n", name); exit(1); }
    if (ascent > 255 || height > 255) { fprintf(stderr, "mkfont: %s metrics out of range\n", name); exit(1); }

    fprintf(out, "static const u8 %s_pix[%d] = {\n", name, total > 0 ? total : 1);
    int n = 0, off = 0;
    for (int i = 0; i < NGLYPH; i++) {
        struct glyph *g = &gl[i];
        for (int k = 0; k < g->w * g->h; k++) {
            fprintf(out, "%s%3d,", n % 16 == 0 ? "\n    " : " ", g->pix[k]);
            n++;
        }
    }
    fprintf(out, "\n};\n");

    fprintf(out, "static const struct ui_glyph %s_glyphs[%d] = {\n", name, NGLYPH);
    for (int i = 0; i < NGLYPH; i++) {
        struct glyph *g = &gl[i];
        fprintf(out, "    { %d, %d, %d, %d, %d, %d },   /* %d */\n",
                g->adv, g->w, g->h, g->xoff, g->yoff, off, FIRST + i);
        off += g->w * g->h;
    }
    fprintf(out, "};\n");
    fprintf(out, "const struct ui_face ui_face_%s = { %d, %d, %s_glyphs, %s_pix };\n\n",
            name, ascent, height, name, name);
    free(ttf);
}

int main(int argc, char **argv)
{
    if (argc != 4) { fprintf(stderr, "usage: mkfont <out.c> <regular.ttf> <bold.ttf>\n"); return 1; }
    FILE *out = fopen(argv[1], "w");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "/* Generated by tools/mkfont from DejaVu Sans (see fonts/LICENSE-DejaVu).  Do not edit. */\n");
    fprintf(out, "#include \"gui/fontdata.h\"\n\n");
    emit_face(out, "regular", argv[2], 14);       /* body text and UI */
    emit_face(out, "bold", argv[3], 14);
    emit_face(out, "large", argv[2], 20);         /* headings */
    emit_face(out, "large_bold", argv[3], 20);
    fclose(out);
    return 0;
}
