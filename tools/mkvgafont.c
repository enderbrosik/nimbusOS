/* NimbusOS - build-time 8x16 bitmap font (host tool).
 *
 * PCs hand the kernel the VGA ROM's 8x16 font; the Raspberry Pi has no such
 * ROM, so its build rasterises DejaVu Sans Mono into the same layout: 256
 * glyphs of 16 rows, one byte per row, bit 7 = leftmost pixel.
 *
 *   usage: mkvgafont <out.c> <mono.ttf>
 */
#define STB_TRUETYPE_IMPLEMENTATION
#include "third_party/stb/stb_truetype.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: mkvgafont <out.c> <mono.ttf>\n"); return 2; }
    FILE *f = fopen(argv[2], "rb");
    if (!f) { perror(argv[2]); return 1; }
    fseek(f, 0, SEEK_END); long len = ftell(f); fseek(f, 0, SEEK_SET);
    unsigned char *ttf = malloc(len);
    if (fread(ttf, 1, len, f) != (size_t)len) return 1;
    fclose(f);
    stbtt_fontinfo fi;
    if (!stbtt_InitFont(&fi, ttf, 0)) { fprintf(stderr, "bad font\n"); return 1; }
    float scale = stbtt_ScaleForPixelHeight(&fi, 15.0f);
    int asc, desc, gap;
    stbtt_GetFontVMetrics(&fi, &asc, &desc, &gap);
    int base = (int)(asc * scale + 0.5f);
    static unsigned char font[256 * 16];
    for (int c = 32; c < 256; c++) {
        if (c >= 0x7F && c < 0xA0) continue;
        int w, h, xo, yo;
        unsigned char *bm = stbtt_GetCodepointBitmap(&fi, scale, scale, c, &w, &h, &xo, &yo);
        if (!bm) continue;
        int adv, lsb;
        stbtt_GetCodepointHMetrics(&fi, c, &adv, &lsb);
        int x0 = (8 - (int)(adv * scale + 0.5f)) / 2 + xo;
        for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++) {
                int cx = x0 + x, cy = base + yo + y;
                if (cx < 0 || cx > 7 || cy < 0 || cy > 15) continue;
                if (bm[y * w + x] >= 100) font[c * 16 + cy] |= 0x80 >> cx;
            }
        stbtt_FreeBitmap(bm, NULL);
    }
    FILE *o = fopen(argv[1], "w");
    if (!o) { perror(argv[1]); return 1; }
    fprintf(o, "/* Generated by tools/mkvgafont from DejaVu Sans Mono - do not edit. */\n");
    fprintf(o, "const unsigned char pi_vga_font[4096] = {\n");
    for (int i = 0; i < 4096; i++) fprintf(o, "0x%02x,%s", font[i], (i % 16 == 15) ? "\n" : "");
    fprintf(o, "};\n");
    fclose(o);
    return 0;
}
